export const LANGUAGES = [
  { code: 'no', flag: '🇳🇴', label: 'Norsk' },
  { code: 'en', flag: '🇬🇧', label: 'English' },
  { code: 'de', flag: '🇩🇪', label: 'Deutsch' },
  { code: 'fr', flag: '🇫🇷', label: 'Français' },
  { code: 'es', flag: '🇪🇸', label: 'Español' },
];

export const DEFAULT_LANG = 'no';

export function getLang() {
  const saved = localStorage.getItem('codestack_lang');
  return LANGUAGES.some((language) => language.code === saved) ? saved : DEFAULT_LANG;
}

export function setLang(code) {
  const next = LANGUAGES.some((language) => language.code === code) ? code : DEFAULT_LANG;
  localStorage.setItem('codestack_lang', next);
  return next;
}

